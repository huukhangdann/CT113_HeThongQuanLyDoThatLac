function initLocationCascade({
    buildingSelect,
    floorSelect,
    roomSelect,
    onChange = () => {},
    placeholders = {},
    allowEmptyBuildingSelection = false
}) {
    if (!buildingSelect || !floorSelect || !roomSelect) {
        throw new Error("Cần truyền đủ select tòa nhà, tầng và phòng.");
    }

    const placeholderText = {
        building: "-- Chọn tòa nhà --",
        floor: "-- Chọn tầng --",
        room: "-- Chọn phòng / hội trường --",
        ...placeholders
    };
    const getFloorLabel = floor => Number(floor.Tang) === 0 ? "Tầng trệt" : `Tầng ${floor.Tang}`;

    const renderOptions = (select, placeholder, items, getValue, getLabel, placeholderDisabled = true) => {
        select.replaceChildren();
        const placeholderOption = document.createElement("option");
        placeholderOption.value = "";
        placeholderOption.textContent = placeholder;
        placeholderOption.disabled = placeholderDisabled;
        placeholderOption.selected = true;
        select.appendChild(placeholderOption);

        items.forEach(item => {
            const option = document.createElement("option");
            option.value = getValue(item);
            option.textContent = getLabel(item);
            select.appendChild(option);
        });

        select._syncCustomDropdown?.();
    };

    const resetRooms = () => {
        renderOptions(roomSelect, placeholderText.room, [], room => room.Phong_id, room => room.Phong);
        roomSelect.disabled = true;
    };

    renderOptions(
        buildingSelect,
        placeholderText.building,
        Object.values(toa),
        building => building.Toa_ID,
        building => `${building.Toa_Ten} (${building.Toa_ID})`,
        !allowEmptyBuildingSelection
    );
    renderOptions(floorSelect, placeholderText.floor, [], floor => floor.Tang_id, getFloorLabel);
    resetRooms();
    floorSelect.disabled = true;

    const notifyChange = () => {
        onChange({
            buildingId: buildingSelect.value,
            floorId: floorSelect.value,
            roomId: roomSelect.value,
            buildingName: buildingSelect.value ? buildingSelect.selectedOptions[0]?.textContent.trim() || "" : "",
            floorName: floorSelect.value ? floorSelect.selectedOptions[0]?.textContent.trim() || "" : "",
            roomName: roomSelect.value ? roomSelect.selectedOptions[0]?.textContent.trim() || "" : ""
        });
    };

    buildingSelect.addEventListener("change", () => {
        const floors = tang[buildingSelect.value] || [];
        renderOptions(floorSelect, placeholderText.floor, floors, floor => floor.Tang_id, getFloorLabel);
        floorSelect.disabled = floors.length === 0;
        resetRooms();
        notifyChange();
    });

    floorSelect.addEventListener("change", () => {
        const rooms = phongData[floorSelect.value] || [];
        renderOptions(roomSelect, placeholderText.room, rooms, room => room.Phong_id, room => room.Phong);
        roomSelect.disabled = rooms.length === 0;
        notifyChange();
    });

    roomSelect.addEventListener("change", notifyChange);
    notifyChange();
}

window.initLocationCascade = initLocationCascade;